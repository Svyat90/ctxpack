export const LANGS = Object.keys(MESSAGES);

// "uk", "uk_UA.UTF-8", "uk-UA" → "uk"; anything else → "en".
export const normLang = value => (String(value || '').toLowerCase().startsWith('uk') ? 'uk' : 'en');

// CLI language: --lang, then CTXPACK_LANG, then the system locale.
export const envLang = () => normLang(process.env.CTXPACK_LANG || process.env.LC_ALL || process.env.LC_MESSAGES || process.env.LANG);

export function t(lang, key, params = {}) {
  const text = MESSAGES[lang]?.[key] ?? MESSAGES.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ''));
}
